    public const string Spanish = "es";
    public const string EnglishCode = "en";

    static readonly CultureInfo EsCulture = CultureInfo.GetCultureInfo("es-ES");
    static readonly CultureInfo EnCulture = CultureInfo.GetCultureInfo("en-GB");

    public static string Language { get; private set; } = Spanish;

    public static bool IsEnglish => Language == EnglishCode;

    /// <summary>Culture for dates and numbers shown to the user.</summary>
    public static CultureInfo Culture => IsEnglish ? EnCulture : EsCulture;

    /// <summary>Raised after the language changed.</summary>
    public static event Action? Changed;

    public static void Set(string? language)
    {
        var next = language == EnglishCode ? EnglishCode : Spanish;
        if (next == Language) return;
        Language = next;
        Changed?.Invoke();
    }

    /// <summary>The text in the current language.</summary>
    public static string T(string text) =>
        IsEnglish && English.TryGetValue(text, out var translated) ? translated : text;

    /// <summary>A text with {0}-style placeholders, translated and then filled in.</summary>
    public static string T(string format, params object?[] args) => string.Format(Culture, T(format), args);

